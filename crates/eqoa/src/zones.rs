/// `ZoneName`'s switch: `None` outside a grid (the caller's 641).
pub fn zone(world: i32, row: i32, col: i32) -> Option<u16> {
    if row < 0 || col < 0 {
        return None;
    }
    let (r, c) = (row as usize, col as usize);
    match world {
        0 => ZONES0.get(r).and_then(|x| x.get(c)).copied(),
        1 => ZONES1.get(r).and_then(|x| x.get(c)).copied(),
        2 => ZONES2.get(r).and_then(|x| x.get(c)).copied(),
        3 => ZONES3.get(r).and_then(|x| x.get(c)).copied(),
        4 => ZONES4.get(r).and_then(|x| x.get(c)).copied(),
        5 => ZONES5.get(r).and_then(|x| x.get(c)).copied(),
        _ => None,
    }
}
